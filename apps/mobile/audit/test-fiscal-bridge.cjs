const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),Module=require("node:module"),ts=require("typescript");
let response={ok:true,id:"invoice_1"},calls=[];
const p=path.resolve(__dirname,"../src/lib/fiscalInvoice.ts");
const code=ts.transpileModule(fs.readFileSync(p,"utf8"),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const mod=new Module(p,module);mod.filename=p;mod.paths=Module._nodeModulePaths(path.dirname(p));
mod.require=name=>name==="./api"?{request:async(path,init)=>{calls.push({path,init});return response;}}:require(name);
mod._compile(code,p);
(async()=>{
await mod.exports.saveInvoiceDraftOnServer("BA-2026-001",{id:"invoice_1",rechnungNr:"RE-001",fiscalStatus:"AUSGESTELLT"});
assert.match(calls[0].path,/\/save$/);
assert.equal(JSON.parse(calls[0].init.body).fiscalStatus,"ENTWURF");
assert.equal(JSON.parse(calls[0].init.body).nr,"RE-001");
response={ok:true,id:"wrong"};
await assert.rejects(()=>mod.exports.saveInvoiceDraftOnServer("BA-2026-001",{id:"invoice_1",rechnungNr:"RE-001"}),/NOT_CONFIRMED/);
await assert.rejects(()=>mod.exports.saveInvoiceDraftOnServer("../other",{id:"invoice_1",rechnungNr:"RE-001"}),/INVALID_PROJECT/);
response={ok:false,fiscalStatus:"AUSGESTELLT",error:"ACCOUNTING_RECONCILIATION_REQUIRED"};
const r=await mod.exports.issueInvoiceOnServer("BA-2026-001","invoice_1");
assert.equal(r.issued,true);assert.equal(r.reconciliationRequired,true);
response={ok:true,fiscalStatus:"ENTWURF"};
await assert.rejects(()=>mod.exports.issueInvoiceOnServer("BA-2026-001","invoice_1"),/NOT_CONFIRMED/);
console.log("PASS fiscal bridge: draft acknowledgement, no fake issuance, 202 reconciliation");
})().catch(e=>{console.error(e);process.exitCode=1;});
