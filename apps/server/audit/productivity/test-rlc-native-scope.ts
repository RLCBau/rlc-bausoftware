import assert from 'node:assert/strict';
import {checkRlcNativeScope} from '../../src/kalkulation/autonomous/rlcNativeScopeGate';
import {calculateRlcNativeRecipe} from '../../src/kalkulation/autonomous/rlcNativeRecipes';
const row={posNr:'1',kurztext:'Asphaltdecksch. aus AC 11 D S herstellen Dicke 4 cm',einheit:'m2',menge:100};
const preview=calculateRlcNativeRecipe(row);
assert(preview);
const scope=checkRlcNativeScope('asphalt_layer',['material','walze','lohn'],preview.costLines);
assert.deepEqual(scope.missing,['fracht','fertiger','baustellenlogistik']);
assert.equal(scope.economicallyApproved,false);
assert.equal(scope.complete,false);
assert(preview.warnings.includes('RLC_NATIVE_MISSING_FRACHT'));
assert(preview.warnings.includes('RLC_NATIVE_MISSING_FERTIGER'));
assert(preview.warnings.includes('RLC_NATIVE_MISSING_BAUSTELLENLOGISTIK'));
assert.equal(checkRlcNativeScope('asphalt_layer',['material','fracht','fertiger','walze','lohn','baustellenlogistik'],preview.costLines).complete,false);
assert.equal(checkRlcNativeScope('material_ex_works',['material'],preview.costLines).economicallyApproved,false);
console.log('RLC_NATIVE_SCOPE_GATE_PASS');
