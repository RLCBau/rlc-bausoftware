import assert from 'node:assert/strict';
import {calculateRlcMotorWithContext} from '../../src/kalkulation/rlcMotor';
import {analyzeRlcProjectContext} from '../../src/kalkulation/autonomous/projectContextAnalyzer';
import {inspectRlcMotorConsumptionIntegrity} from '../../src/kalkulation/autonomous/rlcMotorConsumptionIntegrity';
const row={posNr:'1',kurztext:'Asphalt AC 16 T liefern und einbauen',einheit:'t',menge:10};
const context=analyzeRlcProjectContext([row],'Straßenbau');
const result=calculateRlcMotorWithContext(row,context,[row]);
assert(result);
const material=result.costLines.find(x=>x.name.includes('AC 16 T'));
assert(material);
assert.equal(material.unitPrice,103.1);
assert.equal(material.consumption?.resourceQtyPerGaebUnit,1);
assert.equal(material.consumption?.resourceUnit,'t');
assert.equal(material.consumption?.status,'recipe_assumption');
assert.equal(inspectRlcMotorConsumptionIntegrity(result).issues.length,0);
const other={...row,kurztext:'Asphalt AC 11 D N liefern und einbauen'};
const second=calculateRlcMotorWithContext(other,context,[other]);
assert.equal(second?.costLines.find(x=>x.name.includes('AC 11 D N'))?.unitPrice,145);
assert(result.unitPrice!==second?.unitPrice);
console.log('RLC_ASPHALT_URK_GRADE_PASS',result.unitPrice,second?.unitPrice);
